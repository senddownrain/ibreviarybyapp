/// Geometry shared by floating bottom controls. The content of each control
/// remains specific to its book or search domain.
abstract final class BottomControlGeometry {
  static const double gap = 14;
  static const double maxWidth = 520;
  static const double radius = 28;
  static const double minimumTarget = 48;
  static const double searchHeight = 58;
  static const double contentGap = 24;
}
