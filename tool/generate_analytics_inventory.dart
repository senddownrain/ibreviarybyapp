// Regenerates lib/analytics/public_inventory.dart from the web inventory copy.
//
//   dart run tool/generate_analytics_inventory.dart <path-to-public-inventory.json>
//
// Copy the web file (mybrev: src/utils/analytics/public-inventory.json) to
// test/fixtures/analytics/ first; test/analytics/public_inventory_test.dart
// fails when the generated set and the fixture differ.
import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  final source = args.isEmpty
      ? 'test/fixtures/analytics/public-inventory.json'
      : args.first;
  final data =
      jsonDecode(File(source).readAsStringSync()) as Map<String, dynamic>;
  final ids = (data['ids'] as List).cast<String>();
  final out = StringBuffer()
    ..writeln(
      '// GENERATED by tool/generate_analytics_inventory.dart. Do not edit.',
    )
    ..writeln(
      '// Public content_id inventory of analytics contract v2 (web reference:',
    )
    ..writeln('// src/utils/analytics/public-inventory.json).')
    ..writeln('//')
    ..writeln(
      '// source bundle content version: ${(data['source'] as Map)['bundleContentVersion']}',
    )
    ..writeln('// sha256 of the sorted id list: ${data['sha256']}')
    ..writeln()
    ..writeln('const String kAnalyticsInventorySha256 = \'${data['sha256']}\';')
    ..writeln()
    ..writeln('const Set<String> kAnalyticsPublicIds = {');
  for (final id in ids) {
    out.writeln("  '$id',");
  }
  out.writeln('};');
  File('lib/analytics/public_inventory.dart').writeAsStringSync(out.toString());
  stdout.writeln(
    'wrote lib/analytics/public_inventory.dart: ${ids.length} ids',
  );
}
